namespace Karvon.Skills;

/// <summary>What a generated memory file is, against its source.</summary>
public enum MemoryState
{
    Missing,

    /// <summary>Generated from the source, and what Karvon would write now.</summary>
    UpToDate,

    /// <summary>Generated from the source, which changed since (or the skills did).</summary>
    OutOfDate,

    /// <summary>Written by hand: Karvon leaves it unless the user says otherwise.</summary>
    HandWritten,
}

/// <summary>
/// The agents' memory files: Claude Code reads <c>CLAUDE.md</c>, Codex and others <c>AGENTS.md</c>, Gemini CLI
/// <c>GEMINI.md</c>. Karvon writes the others from one source, with a header saying so and, when the folder has skills
/// (which those agents do not load themselves), a section listing them and where their instructions are.
/// </summary>
public sealed class MemoryFiles(string workspace, string source, Func<IReadOnlyList<Skill>> projectSkills)
{
    public static readonly IReadOnlyList<string> Names = ["CLAUDE.md", "AGENTS.md", "GEMINI.md"];

    const string Marker = "<!-- Generated by Karvon from ";

    public string Source { get; } = source;

    public IEnumerable<string> Targets => Names.Where(f => !string.Equals(f, Source, StringComparison.OrdinalIgnoreCase));

    public string PathOf(string file) => Path.Combine(workspace, file);

    public bool HasSource => File.Exists(PathOf(Source));

    public MemoryState StateOf(string target)
    {
        var file = PathOf(target);
        if (!File.Exists(file))
            return MemoryState.Missing;
        var text = File.ReadAllText(file);
        if (!text.StartsWith(Marker, StringComparison.Ordinal))
            return MemoryState.HandWritten;
        return HasSource && Normal(text) == Normal(Generate()) ? MemoryState.UpToDate : MemoryState.OutOfDate;
    }

    static string Normal(string text) => text.Replace("\r\n", "\n");

    /// <summary>What Karvon writes: the header, the source as it is, and the folder's skills.</summary>
    public string Generate()
    {
        var text = File.ReadAllText(PathOf(Source)).Replace("\r\n", "\n").TrimEnd('\n');
        var generated = $"{Marker}{Source}: edit {Source}, and Karvon writes this file again. -->\n\n{text}\n";
        var skills = projectSkills();
        if (skills.Count > 0)
            generated += "\n## Skills\n\n"
                + "This project has skills: instructions for particular kinds of work. Before you start a task, read the "
                + "SKILL.md of every skill that applies (and the files it points to).\n\n"
                + string.Join("\n", skills.Select(s => $"- `{Path.GetRelativePath(workspace, s.File).Replace('\\', '/')}`: {s.Description}")) + "\n";
        return generated;
    }

    /// <summary>
    /// Writes the targets that are missing (with <paramref name="createMissing"/>) or generated; hand-written ones only with
    /// <paramref name="replaceHandWritten"/>. Returns the files written and those left alone.
    /// </summary>
    public (IReadOnlyList<string> Written, IReadOnlyList<string> Left) Sync(bool createMissing, bool replaceHandWritten)
    {
        var written = new List<string>();
        var left = new List<string>();
        if (!HasSource)
            return (written, left);
        var text = Generate();
        foreach (var target in Targets)
        {
            var state = StateOf(target);
            if (state == MemoryState.UpToDate || state == MemoryState.Missing && !createMissing)
                continue;
            if (state == MemoryState.HandWritten && !replaceHandWritten)
            {
                left.Add(target);
                continue;
            }
            File.WriteAllText(PathOf(target), text);
            written.Add(target);
        }
        return (written, left);
    }
}
